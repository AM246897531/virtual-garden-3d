package app.mishnehtorah

/**
 * Conservative, auditable source navigation for common Rambam intents.
 * Hints only rank VERIFIED passages in the bundled corpus; they never
 * compose a new halakhic ruling. Multi-concept checks prevent confusing
 * similar questions (e.g. Rosh Chodesh in birkat hamazon vs prayer).
 */
internal data class SourceHint(
    val sectionName: String,
    val chapter: Int,
    val halakhah: Int,
    val reason: String,
    val focus: String = ""
)

internal object SmartQueryHints {
    fun forQuestion(query: String): SourceHint? {
        val q = HebrewSearch.normalize(query.replace("ר״ח", "ראש חודש")
            .replace("ר\"ח", "ראש חודש"))
        fun has(vararg phrases: String) = phrases.any { q.contains(HebrewSearch.normalize(it)) }
        fun source(section: String, chapter: Int, law: Int, focus: String = "") =
            SourceHint("הלכות $section", chapter, law, "topic match: $section/$chapter/$law", focus)

        val blessing = has("ברכת המזון", "ברכת מזון", "ברכתי על המזון", "ברכת האוכל")
        val forgot = has("שכח", "שכחתי", "לא אמר", "לא הזכר", "דילג", "פספס", "לא אמרתי")
        val month = has("ראש חודש", "ראש חדש", "ראשי חדשים", "ר ח")
        val yaaleh = has("יעלה ויבוא", "יעלה ויבא")
        val shema = has("קריאת שמע", "לקרוא שמע", "קוראים שמע", "שמע ישראל")
        val prayer = has("תפילה", "תפלת", "להתפלל", "תפילות")
        val shacharit = has("שחרית", "תפילת השחר", "תפלת השחר", "תפילה בבוקר")
        val shabbat = has("שבת", "שבת קודש", "ליל שבת")
        val hanukkah = has("חנוכה", "חנכה")
        val sukkah = has("סוכה", "סכה")
        val tefillin = has("תפילין", "תפלין")
        val mezuzah = has("מזוזה", "מזוזות")
        val pesach = has("פסח", "ליל הסדר", "ליל חמישה עשר")
        val shofar = has("שופר", "תקיעות", "תרועה") && has("ראש השנה", "שופר")
        val repentance = has("תשובה", "בתשובה", "להתוודות", "וידוי", "חטא")

        // Most specific cases first, so related laws do not shadow each other.
        if (blessing && forgot && (month || yaaleh))
            return source("ברכות", 2, 13, "בראשי חדשים שכח")
        if ((blessing || has("סעודה", "סעודת")) && forgot &&
            (shabbat || has("רצה והחליצנו", "הזכרת שבת")))
            return source("ברכות", 2, 12, "שכח ולא הזכיר בשבת")
        if (blessing && has("מקום", "בדרך", "הליכה", "מהלך", "טיול", "איפה צריך", "היכן צריך"))
            return source("ברכות", 4, 1, "במקום שאכל")
        if (blessing && has("סדר", "כמה ברכות", "ראשונה", "שניה", "איזה ברכות"))
            return source("ברכות", 2, 1, "סדר ברכת המזון")
        if (blessing && has("מן התורה", "מדאורייתא", "חייב", "חובה", "שבע", "מצווה"))
            return source("ברכות", 1, 1, "ואכלת ושבעת וברכת")
        if (has("ליטול ידיים", "נטילת ידיים", "נטילת ידים", "נוטלים ידיים") &&
            has("לחם", "פת", "סעודה", "לאכול", "אכילת"))
            return source("ברכות", 6, 1, "צריך נטילת ידים")

        if (shema && has("כוונה", "כוונ", "התכוונ", "מחשבה", "פסוק ראשון", "בלי מחשבה", "יצאתי"))
            return source("קריאת שמע", 2, 1, "לא כון לבו בפסוק ראשון")
        if (shema && has("כמה פעמים", "פעמיים", "פעמים ביום", "כל יום", "מספר פעמים"))
            return source("קריאת שמע", 1, 1, "פעמים בכל יום")
        if (shema && has("בלילה", "ערבית", "בערב", "זמן ערב"))
            return source("קריאת שמע", 1, 9, "משעה")
        if (shema && has("בבוקר", "בשחרית", "שחרית", "הנץ"))
            return source("קריאת שמע", 1, 11, "זמן קריאת שמע")
        if ((prayer || shacharit) && has("מעכב", "מעכבים", "דברים מעכבין"))
            return source("תפילה וברכת כהנים", 4, 1, "חמשה דברים מעכבין")
        if (shacharit && has("מתי", "זמן", "עד איזה", "שעה", "הנץ", "זריחה", "להשלים"))
            return source("תפילה וברכת כהנים", 3, 1, "תפלת השחר")
        if (prayer && has("בכל יום", "כל יום", "מחויב", "חייב", "חובה", "מצות עשה"))
            return source("תפילה וברכת כהנים", 1, 1, "מצות עשה להתפלל בכל יום")

        if (shabbat && has("חולה", "סכנת", "סכנה", "להציל", "פיקוח נפש", "חיים")) {
            val uncertainty = has("ספק", "לא בטוח", "לא יודעים", "לא ידוע", "אולי", "מסופק")
            return source("שבת", 2, 1,
                if (uncertainty) "ספק שהוא צריך לחלל" else "סכנת נפשות")
        }
        if (shabbat && has("שלושים ותשע", "שלשים ותשע", "39", "מלאכות שבת", "אבות מלאכות"))
            return source("שבת", 7, 1, "ארבעים חסר אחת")
        if (shabbat && has("לפני", "בערב", "קודם", "כניסת") &&
            has("מלאכה", "עבודה", "פעולה", "להכין", "להתחיל") &&
            has("תסתיים", "תימשך", "ממשיכה", "נגמרת", "מאליה", "שתסתיים", "תמשיך"))
            return source("שבת", 3, 1, "נגמרת מאליה")
        if (shabbat && has("נר", "נרות", "להדליק") &&
            has("צריך", "חייב", "חובה", "מנהג", "מצווה", "הדלקת"))
            return source("שבת", 5, 1, "נר בשבת")
        if (has("קידוש") && has("אוכל", "לאכול", "שתיה", "לשתות", "טועמ", "לשתות יין") &&
            has("לפני", "קודם", "בלי", "טרם", "עד"))
            return source("שבת", 29, 5, "עד שיקדש")

        if (hanukkah && has("כמה", "מספר", "מנין") && has("נר", "נרות", "מדליק", "להדליק"))
            return source("מגילה וחנוכה", 4, 1, "כמה נרות הוא מדליק")
        if (hanukkah && has("נר", "נרות", "מדליק", "להדליק") &&
            has("מתי", "זמן", "שעה", "שקיעה", "שוקעת", "עד מתי"))
            return source("מגילה וחנוכה", 4, 5, "עם שקיעתה")
        if (has("מגילה", "המגילה") && has("סדר", "למפרע", "דילג", "פסוקים", "לא לפי"))
            return source("מגילה וחנוכה", 2, 1, "הקורא את המגלה למפרע")
        if (has("מגילה", "המגילה") && has("חייב", "חובה", "מי חייב", "מצווה"))
            return source("מגילה וחנוכה", 1, 1, "והכל חיבים בקריאתה")

        if (pesach && has("יציאת מצרים", "לספר על", "לספר את", "סיפור יציאת", "סיפור הנסים"))
            return source("חמץ ומצה", 7, 1, "לספר בנסים ונפלאות")
        if (pesach && has("חמץ") && has("להשבית", "ביעור", "לבער", "מתי צריך", "להוציא"))
            return source("חמץ ומצה", 2, 1, "להשבית החמץ")
        if (pesach && has("חמץ") && has("לאכול", "אכילה", "אסור", "כזית"))
            return source("חמץ ומצה", 1, 1, "כל האוכל כזית חמץ")
        if (pesach && has("מצה", "מצות") && has("ליל", "מצווה", "מצות", "אכילה", "אכילת"))
            return source("חמץ ומצה", 6, 1, "לאכל מצה בליל")

        if (shofar && has("כמה", "מספר", "תקיעות") && has("תקיעות", "כמה תקיעות", "תשע"))
            return source("שופר וסוכה ולולב", 3, 1, "תשע תקיעות")
        if (shofar && has("מצווה", "מצות", "שמיעת", "לשמוע", "חובה"))
            return source("שופר וסוכה ולולב", 1, 1, "לשמע תרועת השופר")
        if (sukkah && has("גובה", "גובהה", "גבוה", "אמות", "עשרים", "מקסימלי", "כמה גבוהה"))
            return source("שופר וסוכה ולולב", 4, 1, "ולא יתר על עשרים אמה")
        if (sukkah && has("סכך", "סככ", "מסככים", "לעשות סכך", "ממה"))
            return source("שופר וסוכה ולולב", 5, 1, "אין מסככין אלא")
        if (has("ציצית", "ציציות") && has("איזה בגד", "בגד", "כסות", "ארבע כנפות", "חייב"))
            return source("ציצית", 3, 1, "ארבע כנפים")
        if (has("ציצית", "תכלת") && has("תכלת", "כחול", "צבע"))
            return source("ציצית", 2, 1, "הצמר הצבוע")

        if (tefillin && has("ראש", "על המצח", "הקדקד", "למעלה", "היכן", "איפה", "מקום"))
            return source("תפילין ומזוזה וספר תורה", 4, 1, "על הקדקד")
        if (mezuzah && has("מה כותבים", "פרשיות", "כותב", "כותבים"))
            return source("תפילין ומזוזה וספר תורה", 5, 1, "שתי פרשיות")
        if (mezuzah && has("בית", "דירה", "חדר", "תנאים", "איזה תנאי"))
            return source("תפילין ומזוזה וספר תורה", 6, 1, "עשרה תנאין יש בבית")
        if (has("ספר תורה") && has("לכתוב", "כתיבה", "מצווה לכתוב", "לעצמי", "מצות עשה"))
            return source("תפילין ומזוזה וספר תורה", 7, 1, "לכתוב ספר תורה לעצמו")

        if (repentance && has("וידוי", "להתוודות", "מתוודה", "חטא", "שחטא") &&
            has("איך", "צריך", "חייב", "כאשר", "חוזר"))
            return source("תשובה", 1, 1, "חיב להתודות")
        if (repentance && has("שלמה", "גמורה", "באמת", "מה זה נקרא"))
            return source("תשובה", 2, 1, "אי זו היא תשובה גמורה")
        if (has("בחירה", "לעשות טוב או רע", "להיות צדיק", "הבחירה לעשות") &&
            has("אדם", "עצמו", "טוב", "רע", "רשות"))
            return source("תשובה", 5, 1, "רשות לכל אדם נתונה")

        if (has("תורה", "ללמוד", "ללמד") && has("אבא", "אביו", "אב", "בנו", "ילד") &&
            has("ללמד", "ללמוד", "חייב", "מצווה"))
            return source("תלמוד תורה", 1, 1, "אביו חיב ללמדו תורה")
        if (has("רב", "הרב", "רבו", "מורה שלמד") &&
            has("לכבד", "לכבד את הרב", "כבוד", "יותר מאבא", "אביו"))
            return source("תלמוד תורה", 5, 1, "בכבוד רבו ויראתו")
        if (has("חברים", "חבריו", "חברה", "סביבה", "רעיו") &&
            has("משפיעים", "נמשך", "התנהגות", "מעשים", "חינוך", "להתנהג"))
            return source("דעות", 6, 1, "להיות נמשך בדעותיו ובמעשיו")
        if (has("לשון הרע", "לשון רע", "רכילות") &&
            has("מותר", "אסור", "לספר", "לומר", "לדבר", "מה זה"))
            return source("דעות", 7, 2, "לשון הרע")
        if (has("צדקה", "עניים", "לעני") && has("לתת", "לתרום", "מצווה", "חובה", "לעניים"))
            return source("מתנות עניים", 7, 1, "לתן צדקה לעניים")
        if (has("גזלה", "גזילה", "גזל", "לקח רכוש", "לקח רכוש מחבר", "לקח דבר") &&
            has("להחזיר", "השבה", "חייב", "בלי רשות", "גנב", "המקור"))
            return source("גזילה ואבידה", 1, 1, "אם גזל חיב להחזיר")
        if (has("תענית", "תעניות", "צרה", "ציבור", "צבור") &&
            has("ציבור", "צבור", "צרה", "להריע", "תפילה", "לזעוק"))
            return source("תעניות", 1, 1, "על כל צרה שתבוא על הצבור")
        return null
    }
}
